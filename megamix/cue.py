"""Multi-WAV audio CUE sheets, using only relative final-output filenames."""
import hashlib
import json
import os
from pathlib import Path
import re
import uuid
from . import __version__

CUE_NAME = 'MegaMix.cue'
ENCODINGS = {'auto', 'utf-8-sig', 'cp1252'}

def atomic_bytes(path, data):
    path = Path(path)
    temporary = path.with_name(path.name + '.' + uuid.uuid4().hex + '.tmp')
    try:
        with temporary.open('xb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)

def cue_text(value):
    """CD-Text-safe quoted metadata, without ambiguous backslash escaping."""
    value = re.sub(r'[\x00-\x1f\x7f-\x9f]', ' ', str(value or ''))
    return ' '.join(value.replace('"', "'").split())[:80]

def write_cue(project, directory, encoding='auto'):
    # Local import avoids a cycle; the engine also calls this after WAV verification.
    from .engine import filename, wave_info
    directory = Path(directory)
    if encoding not in ENCODINGS:
        raise ValueError('CUE encoding must be auto, utf-8-sig or cp1252.')
    tracks = project['tracks']
    if not 1 <= len(tracks) <= 99:
        raise ValueError('A CUE sheet requires 1 to 99 tracks.')
    artists = [cue_text(t.get('artist', '')) for t in tracks]
    known_artists = {artist.casefold() for artist in artists if artist}
    performer = artists[0] if all(artists) and len(known_artists) == 1 else 'Various Artists' if len(known_artists) > 1 else ''
    lines = [f'REM COMMENT "Generated by MegaMix TUI {__version__}"',
             'REM COMMENT "Trailing pauses are already embedded in the WAV files."',
             'REM COMMENT "Burn in Disc-At-Once mode without extra inter-track gaps."',
             f'TITLE "{cue_text(project["name"])}"']
    if performer:
        lines.append(f'PERFORMER "{performer}"')
    samples = 0
    for number, (track, artist) in enumerate(zip(tracks, artists), 1):
        if track['order'] != number:
            raise ValueError('CUE track order must be sequential from 1. Prepare the project again.')
        name = filename(track, '.wav')
        if Path(name).name != name or re.search(r'["\x00-\x1f\x7f-\x9f]', name):
            raise ValueError('A final WAV filename cannot be represented safely in a CUE sheet.')
        path = directory / name
        if path.is_symlink():
            raise ValueError('CUE sources must be local output WAVs, not symbolic links.')
        wave = wave_info(path)
        if wave['samples'] % 588:
            raise ValueError(f'CUE source is not aligned to CD frames: {name}')
        samples += wave['samples']
        lines += [f'FILE "{name}" WAVE', f'  TRACK {number:02} AUDIO',
                  f'    TITLE "{cue_text(track["title"])}"', f'    PERFORMER "{artist}"',
                  '    INDEX 01 00:00:00']
    # Explicit Windows line endings on every OS. A BOM identifies Unicode text.
    text = '\r\n'.join(lines) + '\r\n'
    if encoding == 'auto':
        try:
            text.encode('cp1252')
            encoding = 'cp1252'
        except UnicodeEncodeError:
            encoding = 'utf-8-sig'
    try:
        data = text.encode(encoding)
    except UnicodeEncodeError as error:
        raise ValueError('These filenames or CD-Text cannot be represented in Windows-1252. Use UTF-8 CUE output.') from error
    atomic_bytes(directory / CUE_NAME, data)
    instructions = f'''BURN THIS COMPILATION WITH EXACT AUDIO COPY

1. Keep {CUE_NAME} and all numbered WAV files together in this folder.
2. Open EAC's Tools > Write CD-R window (or drag the CUE onto EAC).
3. Load {CUE_NAME} as the CUE sheet. Do not append the WAVs separately.
4. Check track count, order, titles and artists before writing.
5. Use Disc-At-Once and disable any option that adds extra 2-second gaps.
   Pauses and CD-frame alignment are already included in the audio files.
6. Enable CD-Text if wanted and supported by your writer. The CUE supplies
   disc/track titles and performers. Actual CD-Text support depends on EAC,
   its write engine and the drive. Original full metadata remains in the project.

CUE encoding: {encoding}. UTF-8 mode includes a BOM; line endings are CRLF.
Automatic mode prefers Windows-1252 when every filename and CD-Text field fits;
otherwise it preserves all characters as UTF-8 with a BOM. The TUI's C shortcut
can explicitly select either encoding. Check names in EAC before writing.
Do not rename the WAVs without regenerating the CUE. Move the whole folder.

No extra PREGAP, POSTGAP or INDEX 00 is created. INDEX 01 is relative to each
separate WAV file, not a cumulative disc offset. The normal first-track lead-in
is handled by the CD writer. The project's pregap setting remains a capacity
reserve and is not an instruction to add audio silence here.

This is an authored compilation layout, not a reconstruction of an original CD's
subcode, ISRC, barcode, pre-emphasis or hidden tracks. Those values are not invented.
Native EAC loading and a physical burn have not been tested in this delivery.
'''
    atomic_bytes(directory / 'BURN_WITH_EAC.txt', instructions.replace('\n', '\r\n').encode('utf-8-sig'))
    return dict(cueFile=CUE_NAME, cueEncoding=encoding, cueSHA256=hashlib.sha256(data).hexdigest(),
                cueTrackCount=len(tracks), totalSamples=samples, totalCdFrames=samples // 588)

def regenerate_cue(project, encoding='auto'):
    """Add/repair a CUE in existing verified output without re-encoding audio."""
    from .engine import filename, wave_info
    if project['status'] != 'Ready' or not project['outputPath']:
        raise ValueError('Complete CD preparation before generating a CUE.')
    directory = Path(project['outputPath'])
    marker = directory / 'VERIFIED.json'
    verified = json.loads(marker.read_text(encoding='utf-8-sig'))
    for key in ['totalSamples', 'totalCdFrames']:
        if verified.get(key) != project[key]:
            raise ValueError('Output verification does not match the current project.')
    if verified.get('projectId') != project['id'] or verified.get('runId') != project['runId'] or verified.get('trackCount') != len(project['tracks']):
        raise ValueError('Output verification belongs to another compilation or run.')
    samples = sum(wave_info(directory / filename(t, '.wav'))['samples'] for t in project['tracks'])
    if samples != project['totalSamples'] or samples % 588 or samples // 588 != project['totalCdFrames']:
        raise ValueError('Output WAV lengths changed. Prepare and verify the compilation again.')
    details = write_cue(project, directory, encoding)
    verified.update(details)
    atomic_bytes(marker, (json.dumps(verified, indent=2) + '\n').encode('utf-8'))
    return details
